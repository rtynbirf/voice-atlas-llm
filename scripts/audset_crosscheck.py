def fuzzy(a, b):
    """нормализованные строки: точное вхождение >=8 символов или полное совпадение"""
    if a == b:
        return True
    if len(a) >= 8 and a in b:
        return True
    if len(b) >= 8 and b in a:
        return True
    return False

