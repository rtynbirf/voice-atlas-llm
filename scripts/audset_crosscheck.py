def secs(t):
    m, s = t.split(":")
    return int(m) * 60 + int(s)

def norm(s):
    s = unicodedata.normalize("NFC", s).lower()
    s = re.sub(r"feat\.?\s+outshadow", "", s)
    s = re.sub(r"[^а-яёa-z0-9]", "", s)
    return s

